import { Injectable, Logger, NotFoundException } from '@nestjs/common';
import { EventEmitter2 } from '@nestjs/event-emitter';
import { InjectModel } from '@nestjs/mongoose';
import { Model, Types } from 'mongoose';
import { CursorPage, buildCursorPage, decodeObjectIdCursor } from '../../common/pagination/cursor';
import { DEFAULT_PAGE_SIZE } from '../../common/pagination/pagination-query.dto';
import { MailService } from '../mail/mail.service';
import { UsersService } from '../users/users.service';
import { InboxQueryDto } from './dto/inbox.dto';
import {
  InboxTab,
  NotificationBucket,
  NotificationEntityType,
  NotificationType,
} from './notification-fields';
import { NOTIFICATION_CREATED, NotificationCreatedEvent } from './notification-events';
import { NotificationSettingsService } from './notification-settings.service';
import { Notification, NotificationDocument } from './schemas/notification.schema';

export interface NotificationRecipient {
  userId: Types.ObjectId;
  bucket: NotificationBucket;
}

export interface DeliverNotificationInput {
  workspaceId: Types.ObjectId;
  type: NotificationType;
  entityType: NotificationEntityType;
  entityId: Types.ObjectId;
  /** Null on entries generated by the cron. The actor never notifies themselves. */
  actorId?: Types.ObjectId | null;
  recipients: NotificationRecipient[];
  data?: Record<string, unknown>;
  /** Extra match that, when a row already exists, skips the recipient. */
  dedupe?: Record<string, unknown>;
  mail?: { subject: string; text: string };
}

export interface InboxCounts {
  /** Unread entries of each inbox bucket. */
  primary: number;
  other: number;
  /** Totals of the snoozed and of the cleared tabs. */
  later: number;
  cleared: number;
  unread: number;
}

@Injectable()
export class NotificationsService {
  private readonly logger = new Logger(NotificationsService.name);

  constructor(
    @InjectModel(Notification.name) private readonly model: Model<Notification>,
    private readonly settings: NotificationSettingsService,
    private readonly users: UsersService,
    private readonly mail: MailService,
    private readonly events: EventEmitter2,
  ) {}

  notificationNotFound(): NotFoundException {
    return new NotFoundException({
      code: 'NOTIFICATION_NOT_FOUND',
      message: 'Notificação não encontrada.',
    });
  }

  /**
   * Writes one entry per recipient that wants the type in the inbox and mails the
   * ones that asked for e-mail. The actor is always dropped.
   */
  async deliver(input: DeliverNotificationInput): Promise<NotificationDocument[]> {
    const recipients = this.eligible(input);

    if (recipients.length === 0) {
      return [];
    }

    const preferences = await this.settings.forUsers(recipients.map((one) => one.userId));
    const created: NotificationDocument[] = [];
    const mailTo: Types.ObjectId[] = [];

    for (const recipient of recipients) {
      const channels = preferences.get(String(recipient.userId));

      if (channels?.[input.type].inbox && !(await this.alreadySent(input, recipient.userId))) {
        created.push(await this.write(input, recipient));
      }

      if (channels?.[input.type].email && input.mail) {
        mailTo.push(recipient.userId);
      }
    }

    await this.sendMail(input, mailTo);

    return created;
  }

  async inbox(
    workspaceId: Types.ObjectId,
    userId: Types.ObjectId,
    query: InboxQueryDto,
  ): Promise<CursorPage<NotificationDocument>> {
    const limit = query.limit ?? DEFAULT_PAGE_SIZE;
    const after = query.cursor ? decodeObjectIdCursor(query.cursor) : null;
    const filter = this.tabFilter(workspaceId, userId, query.tab ?? 'primary');
    const docs = await this.model
      .find(after ? { ...filter, _id: { $lt: after } } : filter)
      .sort({ _id: -1 })
      .limit(limit + 1)
      .exec();

    return buildCursorPage(docs, limit, (doc) => ({ id: String(doc._id) }));
  }

  async counts(workspaceId: Types.ObjectId, userId: Types.ObjectId): Promise<InboxCounts> {
    const unread = { readAt: null };
    const [primary, other, later, cleared] = await Promise.all([
      this.model.countDocuments({ ...this.tabFilter(workspaceId, userId, 'primary'), ...unread }),
      this.model.countDocuments({ ...this.tabFilter(workspaceId, userId, 'other'), ...unread }),
      this.model.countDocuments(this.tabFilter(workspaceId, userId, 'later')),
      this.model.countDocuments(this.tabFilter(workspaceId, userId, 'cleared')),
    ]);

    return { primary, other, later, cleared, unread: primary + other };
  }

  markRead(
    workspaceId: Types.ObjectId,
    userId: Types.ObjectId,
    notificationId: Types.ObjectId,
    read: boolean,
  ): Promise<NotificationDocument> {
    return this.patch(workspaceId, userId, notificationId, { readAt: read ? new Date() : null });
  }

  async markAllRead(
    workspaceId: Types.ObjectId,
    userId: Types.ObjectId,
  ): Promise<{ updated: number }> {
    const result = await this.model
      .updateMany({ workspaceId, userId, readAt: null }, { $set: { readAt: new Date() } })
      .exec();

    return { updated: result.modifiedCount };
  }

  snooze(
    workspaceId: Types.ObjectId,
    userId: Types.ObjectId,
    notificationId: Types.ObjectId,
    until: Date,
  ): Promise<NotificationDocument> {
    return this.patch(workspaceId, userId, notificationId, { snoozedUntil: until });
  }

  clear(
    workspaceId: Types.ObjectId,
    userId: Types.ObjectId,
    notificationId: Types.ObjectId,
  ): Promise<NotificationDocument> {
    const now = new Date();

    return this.patch(workspaceId, userId, notificationId, { clearedAt: now, readAt: now });
  }

  private async patch(
    workspaceId: Types.ObjectId,
    userId: Types.ObjectId,
    notificationId: Types.ObjectId,
    changes: Partial<Notification>,
  ): Promise<NotificationDocument> {
    const doc = await this.model
      .findOneAndUpdate(
        { _id: notificationId, workspaceId, userId },
        { $set: changes },
        { new: true },
      )
      .exec();

    if (!doc) {
      throw this.notificationNotFound();
    }

    return doc;
  }

  private tabFilter(
    workspaceId: Types.ObjectId,
    userId: Types.ObjectId,
    tab: InboxTab,
  ): Record<string, unknown> {
    const now = new Date();

    if (tab === 'cleared') {
      return { workspaceId, userId, clearedAt: { $ne: null } };
    }

    if (tab === 'later') {
      return { workspaceId, userId, clearedAt: null, snoozedUntil: { $gt: now } };
    }

    return {
      workspaceId,
      userId,
      bucket: tab,
      clearedAt: null,
      $or: [{ snoozedUntil: null }, { snoozedUntil: { $lte: now } }],
    };
  }

  /** Drops the actor and repeated recipients, keeping the first bucket seen. */
  private eligible(input: DeliverNotificationInput): NotificationRecipient[] {
    const seen = new Set<string>([String(input.actorId ?? '')]);

    return input.recipients.filter((recipient) => {
      const key = String(recipient.userId);

      if (seen.has(key)) {
        return false;
      }

      seen.add(key);

      return true;
    });
  }

  private async alreadySent(
    input: DeliverNotificationInput,
    userId: Types.ObjectId,
  ): Promise<boolean> {
    if (!input.dedupe) {
      return false;
    }

    const found = await this.model.exists({
      workspaceId: input.workspaceId,
      userId,
      type: input.type,
      entityId: input.entityId,
      ...input.dedupe,
    });

    return found !== null;
  }

  private async write(
    input: DeliverNotificationInput,
    recipient: NotificationRecipient,
  ): Promise<NotificationDocument> {
    const doc = await this.model.create({
      workspaceId: input.workspaceId,
      userId: recipient.userId,
      type: input.type,
      entityType: input.entityType,
      entityId: input.entityId,
      actorId: input.actorId ?? null,
      data: input.data ?? {},
      bucket: recipient.bucket,
    });

    this.events.emit(NOTIFICATION_CREATED, {
      workspaceId: doc.workspaceId,
      notificationId: doc._id,
      userId: doc.userId,
      type: doc.type,
      bucket: doc.bucket,
      entityType: doc.entityType,
      entityId: doc.entityId,
      actorId: doc.actorId,
      data: doc.data,
    } satisfies NotificationCreatedEvent);

    return doc;
  }

  /** Mail must never break the request that produced the notification. */
  private async sendMail(
    input: DeliverNotificationInput,
    userIds: Types.ObjectId[],
  ): Promise<void> {
    if (userIds.length === 0 || !input.mail) {
      return;
    }

    const emails = await this.users.emailsByIds(userIds);

    for (const email of emails.values()) {
      try {
        await this.mail.send({ to: email, subject: input.mail.subject, text: input.mail.text });
      } catch (error) {
        this.logger.error(
          `Falha ao enviar e-mail de ${input.type} para ${email}`,
          error instanceof Error ? error.stack : String(error),
        );
      }
    }
  }
}
