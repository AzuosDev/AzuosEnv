import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { HydratedDocument, Schema as MongooseSchema, Types } from 'mongoose';
import { baseSchemaOptions } from '../../../common/schemas/base-schema-options';
import {
  NOTIFICATION_BUCKETS,
  NOTIFICATION_ENTITY_TYPES,
  NOTIFICATION_TYPES,
  NotificationBucket,
  NotificationEntityType,
  NotificationType,
} from '../notification-fields';

@Schema({ collection: 'notifications', ...baseSchemaOptions })
export class Notification {
  @Prop({ type: Types.ObjectId, ref: 'Workspace', required: true, index: true })
  workspaceId: Types.ObjectId;

  /** Who receives the entry; never the actor. */
  @Prop({ type: Types.ObjectId, ref: 'User', required: true, index: true })
  userId: Types.ObjectId;

  @Prop({ type: String, enum: NOTIFICATION_TYPES, required: true })
  type: NotificationType;

  @Prop({ type: String, enum: NOTIFICATION_ENTITY_TYPES, required: true })
  entityType: NotificationEntityType;

  @Prop({ type: Types.ObjectId, required: true, index: true })
  entityId: Types.ObjectId;

  /** Null on entries the system generated by itself (cron, reminders). */
  @Prop({ type: Types.ObjectId, ref: 'User', default: null })
  actorId: Types.ObjectId | null;

  /** Everything the inbox card needs to render without another read. */
  @Prop({ type: MongooseSchema.Types.Mixed, default: {} })
  data: Record<string, unknown>;

  @Prop({ type: String, enum: NOTIFICATION_BUCKETS, required: true, default: 'primary' })
  bucket: NotificationBucket;

  @Prop({ type: Date, default: null })
  readAt: Date | null;

  /** While in the future the entry only shows up on the `later` tab. */
  @Prop({ type: Date, default: null })
  snoozedUntil: Date | null;

  @Prop({ type: Date, default: null })
  clearedAt: Date | null;
}

export type NotificationDocument = HydratedDocument<Notification>;

export const NotificationSchema = SchemaFactory.createForClass(Notification);

NotificationSchema.index({ workspaceId: 1, userId: 1, bucket: 1, _id: -1 });
NotificationSchema.index({ workspaceId: 1, userId: 1, type: 1, entityId: 1 });
